begin;

create table public.requests (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    title text not null constraint requests_title_check check (length(trim(title)) > 0),
    description text not null constraint requests_description_check check (length(trim(description)) > 0),
    category text not null constraint requests_category_check
        check (category in ('Бот', 'Интеграция', 'Отчёт', 'Другое')),
    status text not null default 'Новая' constraint requests_status_check
        check (status in ('Новая', 'В работе', 'Завершена')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table public.services (
    id bigint generated by default as identity primary key,
    name text not null constraint services_name_check check (length(trim(name)) > 0),
    active boolean not null default true
);

create table public.app_admins (
    user_id uuid primary key references auth.users(id) on delete cascade
);

-- Security-definer function allows checking membership without granting
-- clients direct access to the private app_admins table.
create function public.is_app_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.app_admins
        where user_id = (select auth.uid())
    );
$$;

alter table public.requests enable row level security;
alter table public.services enable row level security;
alter table public.app_admins enable row level security;

-- Restrict table access; row-level policies apply on top of grants.
revoke all on public.app_admins from public, anon, authenticated;
revoke all on public.requests from anon, authenticated;
revoke all on public.services from anon, authenticated;

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.requests to authenticated;
grant select on public.services to anon, authenticated;
grant insert, update, delete on public.services to authenticated;
grant usage on sequence public.services_id_seq to authenticated;

revoke all on function public.is_app_admin() from public, anon, authenticated;
grant execute on function public.is_app_admin() to authenticated;

create policy "Users can create own requests"
    on public.requests for insert to authenticated
    with check ((select auth.uid()) = user_id);

create policy "Users can read own requests"
    on public.requests for select to authenticated
    using ((select auth.uid()) = user_id);

create policy "Users can update own requests"
    on public.requests for update to authenticated
    using ((select auth.uid()) = user_id)
    with check ((select auth.uid()) = user_id);

create policy "Users can delete own requests"
    on public.requests for delete to authenticated
    using (user_id = (select auth.uid()));

create policy "Allow reading active services"
    on public.services for select to anon, authenticated
    using (active = true);

create policy "Admins can read all services"
    on public.services for select to authenticated
    using ((select public.is_app_admin()));

create policy "Admins can insert services"
    on public.services for insert to authenticated
    with check ((select public.is_app_admin()));

create policy "Admins can update services"
    on public.services for update to authenticated
    using ((select public.is_app_admin()))
    with check ((select public.is_app_admin()));

create policy "Admins can delete services"
    on public.services for delete to authenticated
    using ((select public.is_app_admin()));

commit;

